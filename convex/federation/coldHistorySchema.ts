import { defineTable } from 'convex/server';
import { v } from 'convex/values';

export const coldHistoryTables = {
  coldBackupChecks: defineTable({
    jobId: v.id('backupLargeJobs'),
    scope: v.string(),
    rootDigest: v.string(),
    root: v.any(),
    aliases: v.any(),
    seenAliases: v.array(v.string()),
    owner: v.any(),
    kind: v.string(),
    sourceScope: v.string(),
    index: v.number(),
    count: v.number(),
    bytes: v.number(),
    chainDigest: v.string(),
    state: v.string(),
    cursor: v.union(v.string(), v.null()),
    sourceCount: v.number(),
    sourcePageNumber: v.number(),
    expectedPageCount: v.optional(v.number()),
  }).index('job_scope', ['jobId', 'scope']).index('job_state', ['jobId', 'state']),
  coldBackupMessageIds: defineTable({
    jobId: v.id('backupLargeJobs'),
    scope: v.string(),
    messageId: v.string(),
  }).index('job_scope_message', ['jobId', 'scope', 'messageId']),
  coldHistoryJobs: defineTable({
    archiveId: v.id('coldHistoryArchives'),
    owner: v.any(),
    source: v.any(),
    kind: v.optional(v.union(v.literal('archive'), v.literal('import'))),
    fileRoot: v.optional(v.any()),
    authorAliases: v.optional(v.array(v.object({ sourceAuthor: v.string(), targetAuthor: v.string() }))),
    seenAliases: v.optional(v.array(v.string())),
    expectedFingerprint: v.optional(v.string()),
    snapshotId: v.string(),
    state: v.string(),
    phase: v.string(),
    revision: v.number(),
    cursor: v.union(v.string(), v.null()),
    pageNumber: v.number(),
    messageOffset: v.number(),
    chunkCount: v.number(),
    count: v.number(),
    bytes: v.number(),
    chainDigest: v.string(),
    verifiedChunks: v.number(),
    createdAt: v.number(),
    updatedAt: v.number(),
    error: v.optional(v.string()),
  }).index('archive', ['archiveId']),
  coldHistoryChunks: defineTable({
    archiveId: v.id('coldHistoryArchives'),
    jobId: v.optional(v.id('coldHistoryJobs')),
    index: v.number(),
    start: v.number(),
    count: v.number(),
    bytes: v.number(),
    digest: v.string(),
    previousDigest: v.string(),
    chainDigest: v.string(),
    signature: v.string(),
    storageId: v.id('_storage'),
    cumulativeBytes: v.optional(v.number()),
  })
    .index('archive_index', ['archiveId', 'index'])
    .index('archive_start', ['archiveId', 'start'])
    .index('storage', ['storageId']),
  coldHistoryMessageIds: defineTable({
    jobId: v.id('coldHistoryJobs'),
    messageId: v.string(),
    expectedHash: v.optional(v.string()),
    targetSeen: v.optional(v.boolean()),
  }).index('job_message', ['jobId', 'messageId']),
  coldHistoryLocks: defineTable({
    key: v.string(),
    jobId: v.id('coldHistoryJobs'),
    createdAt: v.number(),
  }).index('key', ['key']),
};
